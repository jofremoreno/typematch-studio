export type FontCategory = "Sans-serif" | "Serif" | "Mono" | "Display";
export type Suitability = "Print" | "Screen" | "Both";

export interface FontRecord {
  id: string;
  name: string;
  family: string; // CSS font-family value
  classification: FontCategory;
  subclassification: string;
  license: "Free";
  sourceName: "Google Fonts" | "Fontshare" | "Fontsource" | "Official repository";
  sourceUrl: string;
  reference: string;
  personality: string[];
  xHeight: "Low" | "Medium" | "High" | "Very high";
  strokeContrast: "Low" | "Medium" | "High" | "Very high";
  aperture: "Closed" | "Moderate" | "Open" | "Very open";
  width: "Condensed" | "Normal" | "Wide";
  rhythm: "Irregular" | "Regular" | "Even" | "Mechanical";
  spacing: "Tight" | "Normal" | "Generous";
  opticalFeeling: string;
  bestRoles: string[];
  weakRoles: string[];
  readabilityScore: number;
  displayScore: number;
  bodyTextScore: number;
  uiScore: number;
  printScore: number;
  screenScore: number;
  versatilityScore: number;
  contrastTolerance: "Low" | "Medium" | "High";
  pairingDifficulty: "Easy" | "Moderate" | "Hard";
  recommendedContexts: string[];
  avoidContexts: string[];
  /** Best fit medium derived from print/screen scores. */
  bestMedium: Suitability;
}

const f = (r: FontRecord): FontRecord => ({
  ...r,
  bestMedium:
    Math.abs(r.printScore - r.screenScore) < 8
      ? "Both"
      : r.printScore > r.screenScore
        ? "Print"
        : "Screen",
});

