export function isPremiumReference(f: FontRecord): boolean {
  return (
    f.availability === "paid" ||
    f.availability === "trial" ||
    f.availability === "subscription" ||
    f.availability === "inspiration-only"
  );
}

export function getFreeAlternatives(f: FontRecord, limit = 4): FontRecord[] {
  const ids = f.freeAlternatives ?? [];
  const out: FontRecord[] = [];
  for (const id of ids) {
    const r = FONTS_BY_ID[id];
    if (r && !isPremiumReference(r)) out.push(r);
    if (out.length >= limit) break;
  }
  return out;
}

export function findFontByQuery(query: string): FontRecord | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  const exact = FONTS.find((f) => f.name.toLowerCase() === q);
  if (exact) return exact;
  const startsWith = FONTS.find((f) => f.name.toLowerCase().startsWith(q));
  if (startsWith) return startsWith;
  const includes = FONTS.find((f) => f.name.toLowerCase().includes(q));
  return includes ?? null;
}

export function suggestSimilarFree(query: string, limit = 4): FontRecord[] {
  // simple heuristic: prefer versatile, high-quality free defaults
  const fallback = ["inter", "source-serif-4", "ibm-plex-sans", "space-grotesk"];
  return fallback.map((id) => FONTS_BY_ID[id]).filter(Boolean).slice(0, limit);
}